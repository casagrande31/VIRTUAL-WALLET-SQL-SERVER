CREATE SCHEMA WALLET


CREATE TABLE WALLET.MOEDA(
	CODIGOMOEDA VARCHAR(3),
	NOME VARCHAR(200),
	PRIMARY KEY(CODIGOMOEDA)
)


CREATE TABLE WALLET.CLIENTE(
	CODIGOCLIENTE INT IDENTITY,
	NOME VARCHAR(200),
	EMAIL VARCHAR(200),
	CELULAR VARCHAR(50),
	PASSHASH VARCHAR(200),
	MOEDAPRINCIPAL VARCHAR(3),

	FOREIGN KEY (MOEDAPRINCIPAL)
	REFERENCES WALLET.MOEDA(CODIGOMOEDA),
	
	PRIMARY KEY(CODIGOCLIENTE)
)

CREATE TABLE WALLET.PARES_MOEDAS(
	CODIGOMOEDABASE VARCHAR(3),
	CODIGOMOEDADACOTACAO VARCHAR(3),
	VALOR REAL,

	FOREIGN KEY(CODIGOMOEDABASE)
	REFERENCES WALLET.MOEDA(CODIGOMOEDA),

	FOREIGN KEY(CODIGOMOEDADACOTACAO)
	REFERENCES WALLET.MOEDA(CODIGOMOEDA),

	PRIMARY KEY (CODIGOMOEDABASE, CODIGOMOEDADACOTACAO)
)

CREATE TABLE WALLET.CORRETORA(
	CODIGOCORRETORA INT IDENTITY,
	NOME VARCHAR(200),

	PRIMARY KEY(CODIGOCORRETORA)
)

CREATE TABLE WALLET.CARTEIRA(
	ENDERECO VARCHAR(200),
	CODIGOCORRETORA INT,
	CODIGOCLIENTE INT,

	FOREIGN KEY (CODIGOCORRETORA)
	REFERENCES WALLET.CORRETORA(CODIGOCORRETORA),

	FOREIGN KEY (CODIGOCLIENTE)
	REFERENCES WALLET.CLIENTE(CODIGOCLIENTE),

	PRIMARY KEY (ENDERECO)
)

CREATE TABLE WALLET.ITEM_CARTEIRA(
	CODIGOITEMCARTEIRA INT IDENTITY,
	ENDERECO VARCHAR(200),
	CODIGOMOEDA VARCHAR(3),
	QUANTIDADE REAL,

	FOREIGN KEY (ENDERECO)
	REFERENCES WALLET.CARTEIRA(ENDERECO),

	FOREIGN KEY (CODIGOMOEDA)
	REFERENCES WALLET.MOEDA(CODIGOMOEDA),

	PRIMARY KEY(CODIGOITEMCARTEIRA)
)

CREATE INDEX IX_CLIENTE_EMAIL
ON WALLET.CLIENTE (EMAIL);

CREATE INDEX IX_CARTEIRA_CODIGOCLIENTE
ON WALLET.CARTEIRA (CODIGOCLIENTE);

CREATE INDEX IX_ITEM_CARTEIRA_ENDERECO
ON WALLET.ITEM_CARTEIRA (ENDERECO);

