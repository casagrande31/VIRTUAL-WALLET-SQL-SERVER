CREATE FUNCTION WALLET.FN_COTACAO_MOEDA_PRINCIPAL (@CODIGOCLIENTE INT)
RETURNS REAL
AS
BEGIN

    DECLARE @MOEDAPRINCIPAL VARCHAR(3)

    SELECT @MOEDAPRINCIPAL = MOEDAPRINCIPAL
    FROM WALLET.CLIENTE
    WHERE CODIGOCLIENTE = @CODIGOCLIENTE    

    DECLARE @SALDO REAL
    DECLARE @MOEDA VARCHAR(3)

    SELECT 
        @SALDO = IC.QUANTIDADE,
        @MOEDA = IC.CODIGOMOEDA
    FROM WALLET.CARTEIRA CA
    INNER JOIN WALLET.ITEM_CARTEIRA IC
        ON CA.ENDERECO = IC.ENDERECO
    WHERE CA.CODIGOCLIENTE = @CODIGOCLIENTE

    IF @MOEDA = @MOEDAPRINCIPAL
    BEGIN
        RETURN @SALDO
    END

    DECLARE @COTACAO REAL

    SELECT @COTACAO = PM.VALOR
    FROM WALLET.PARES_MOEDAS PM
    WHERE PM.CODIGOMOEDABASE = @MOEDA
      AND PM.CODIGOMOEDADACOTACAO = @MOEDAPRINCIPAL

    RETURN (@SALDO * @COTACAO)

END

SELECT WALLET.FN_COTACAO_MOEDA_PRINCIPAL(3)


CREATE VIEW WALLET.VW_SALDO_CARTEIRA AS
	SELECT
		C.CODIGOCLIENTE,
		C.NOME AS CLIENTE,
		CA.ENDERECO,
		M.NOME AS MOEDA,
		IC.QUANTIDADE,
		WALLET.FN_VALOR_MOEDA_BRL(C.CODIGOCLIENTE) AS VALOR_EM_BRL
	FROM WALLET.CLIENTE C
	INNER JOIN WALLET.CARTEIRA CA
		ON C.CODIGOCLIENTE = CA.CODIGOCLIENTE
	INNER JOIN WALLET.ITEM_CARTEIRA IC
		ON CA.ENDERECO = IC.ENDERECO
	INNER JOIN WALLET.MOEDA M
		ON IC.CODIGOMOEDA = M.CODIGOMOEDA

