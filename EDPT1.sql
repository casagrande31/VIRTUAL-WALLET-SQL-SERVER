CREATE FUNCTION WALLET.FN_VALOR_MOEDA_BRL (@CODIGOCLIENTE INT)
RETURNS REAL
AS
BEGIN

    DECLARE @SALDO REAL
    DECLARE @MOEDA VARCHAR(3)
    DECLARE @COTACAO REAL

    SELECT 
        @SALDO = IC.QUANTIDADE,
        @MOEDA = IC.CODIGOMOEDA
    FROM WALLET.CARTEIRA CA
    INNER JOIN WALLET.ITEM_CARTEIRA IC
        ON CA.ENDERECO = IC.ENDERECO
    WHERE CA.CODIGOCLIENTE = @CODIGOCLIENTE

    IF @MOEDA = 'BRL'
    BEGIN
        RETURN @SALDO
    END

    SELECT @COTACAO = PM.VALOR
    FROM WALLET.PARES_MOEDAS PM
    WHERE PM.CODIGOMOEDABASE = @MOEDA
      AND PM.CODIGOMOEDADACOTACAO = 'BRL'

    RETURN (@SALDO * @COTACAO)

END

